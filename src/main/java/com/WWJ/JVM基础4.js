//运行时数据区
/*
*字节码文件会被类加载器加载到JVM虚拟机的内存当中，然后虚拟机就能执行字节码文件中的指令了
* 会将字节码文件加载到内存中的两块区域：方法区和堆内存
* 又因为JVM虚拟机在运行的时候会去使用这两块内存，所以也将这两块内存称为运行时数据区
* 运行时数据区除了保存字节码信息之外，创建的类的对象也会被放到这个区域中
*
* 运行时数据区分为两大类
* 线程不共享(即每个线程里面都会独立有这三个部分对应的数据，其他线程无法访问该线程的数据，当线程回收时，这三个部分的内存也会被释放):
* 程序计数器、Java虚拟机栈、本地方法栈
*
* 线程共享(只要向这两个区域中存放数据，所有线程都可以访问这些数据，但是存在线程安全问题):
* 堆内存、方法区
*
*
* 应用场景:
* 1、内存飙高
* 2、内存溢出OOM
 */

//程序计数器
/*
* 程序计数器(Program Counter Register)也叫做PC寄存器，每个线程会通过程序计数器记录当前要执行的字节码指令的地址
*字节码指令最初是保存在字节码文件当中的，当类加载器将文件读取到内存后，每条指令都会有一个内存地址,方便后续交给解释器去执行
* 例如:
* 字节码文件中
* 0 iconst_0
* 1 istore_1
* 2 iload_1
* 3 ifne 9 (+6) //将操作数栈中的数和零进行比较，如果相等执行编号6，不相等执行编号9，注意这个指令占了3、4、5三个编号
* 6 iinc 1 by -1
* 9 iinc 1 by 1
* 12 return
* 类加载到内存中后
* 编号/偏移量，会被替换为内存中的地址
* 0x000001f248c072c0 iconst_0
* 会将该内存地址保存在程序计数器中，当解释器将这行的指令执行完之后，
* 程序计数器中就会刷新保存下一行指令的地址
* 解释器就会根据程序机器数中最新的内存地址，去找到对应的下一行指令进行执行
*
* 程序计数器的作用:
* 1、程序计数器可以控制指令的进行，实现分支，跳转、异常等逻辑
* 例如:ifne 9 (+6)//如果等于零，程序计数器就会存放9这行指令的内存地址，反之则会保存6这行的地址
*
* 2、在多线程执行的情况下，Java虚拟机需要通过程序计数器记录CPU切换前解释执行那一句指令并继续解释运行
* 例如:有线程A和线程B
* CPU在从线程A切换成线程B后，线程A的程序计数器会记录当前线程A之后继续执行的指令的内存地址
* 以便于当CPU切换回线程A时，可以直接继续往下执行的指令是什么
* */
内存溢出是指,程序在使用某一块内存区域时，存放的数据需要占用的内存大小超过了虚拟机能提供的内存上限

//直接内存
/*
*直接内存(Direct Memory)并不在<Java虚拟机规范>中存在,所以并不属于Java运行时的内存区域
* 在JDK1.4中引入了NIO机制，使用了直接内存，
* 主要是为了解决以下两个问题
* 1、Java堆中的对象如果不再使用要进行回收，回收时会影响对象的创建和使用(因为GC会暂停所有线程的执行)，
* 直接内存不在Java堆中，所以不会受到GC的影响，直接内存的回收是由操作系统来管理的
* 2、IO操作比如读文件，需要先把文件读入直接内存(缓冲区)再把数据复制到Java堆中
* 现在直接放入直接内存即可，同时Java堆上维护直接内存的引用，减少了数据赋值的开销，写文件也时类似的思路
*即:
* 程序 --->java堆内存--本地文件
*  、        |      /
*    、      |    /写/读
*     、直接内存 /
* 在JDK8之后，直接内存还用于保存方法区中的数据
*
* 要想在直接内存中创建数据，
* 必须使用ByteBuffer类的allocateDirect(size)方法，在直接内存上分配内存空间，并指定内存空间的大小
* 使用Arthas中的memory命令可以查看直接内存的使用情况
* 要查看的属性字段是direct，表示直接内存的使用情况，有used、total、max三个值
*
*
* 测试：直接内存大小分配是否有上限
* public class Test {
*  public static int size=1024*1024*100; //每次创建100mb的直接内存
*  public static List<ByteBuffer> list=new ArrayList<>();
*  public static int count=0;
* public static void main(String[] args) {
*  System.in.read(); //阻塞主线程，等待用户输入
* while(true){
* ByteBuffer byteBuffer=ByteBuffer.allocateDirect(size); //每次创建100mb的直接内存
* list.add(byteBuffer); //将直接内存的引用地址放到集合中，防止GC回收
* count++;
* system.out.println("创建了"+count+"个直接内存对象");
* Thread.sleep(1000); //每次创建完直接内存后休眠1秒，方便查看直接内存的使用情况
* }
*
* 会发现我的系统大概执行40次数左右(即4G)就会发生OOM异常，
* 报错为java.lang.OutOfMemoryError: Direct buffer memory，即直接内存溢出
*
* 直接内存的大小是可以通过JVM参数来设置的，使用-XX:MaxDirectMemorySize参数来设置直接内存的最大值
* 单位k表示千字节，m表示兆字节，g表示千兆字节，以及单位字节(必须是1024的倍数)
* 例如:-XX:MaxDirectMemorySize=1g //将直接内存的最大值设置为1g。
* 在不设置参数的情况下，JVM自动选择最大分配的大小
*
* 建议如果工作中需要使用到NIO机制，最好通过压测决定，将直接内存的最大值设置是多大
* */
